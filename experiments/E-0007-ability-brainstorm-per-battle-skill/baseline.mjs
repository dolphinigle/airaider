const parse = s => { const [star, name, from, target, power, effect, cost, flags] = s.split('|'); return { star: +star, name, from, target, power, effect, cost, flags: flags.split(' ') }; };
export const all = () => SKILLS.map(k => ({ ...k, abilities: k.abilities.map(parse) }));

if (import.meta.url === `file://${process.argv[1]}`) {
  const [cmd, out] = process.argv.slice(2);
  const skills = all();
  if (cmd === 'stats') {
    let n = 0; const byStar = [0, 0, 0, 0, 0, 0], byState = {}; let cd = 0, uses = 0, def = 0;
    for (const k of skills) for (const a of k.abilities) {
      n++; byStar[a.star]++; for (const f of a.flags) byState[f] = (byState[f] || 0) + 1;
      if (/cd [1-9]/.test(a.cost)) cd++; if (/use/.test(a.cost)) uses++; if (/^0 cd/.test(a.cost) && /%/.test(a.power) && !/heal|shield/.test(a.power)) def++;
    }
    console.log(`${skills.length} skills, ${n} abilities (${(n / skills.length).toFixed(1)} each)`);
    console.log(`rarity 1★–4★: ${byStar.slice(1, 5).join(' / ')}  ·  with a cooldown ${cd}  ·  limited uses ${uses}  ·  0-cd attacks ${def}`);
    console.log('flags', byState);
  } else if (cmd === 'html') {
    const { render } = await import('./baseline-page.mjs');
    (await import('node:fs')).writeFileSync(out, render(skills, NEW_STATUSES, CALLS));
    console.log('wrote', out);
  }
}
